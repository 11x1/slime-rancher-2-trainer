#!/usr/bin/env python3
"""Generate the version.dll proxy export table from the REAL system DLL.

Reads C:\\Windows\\System32\\version.dll (or the path given with --source) with
pefile and writes, next to this script:

  version.def          module-definition file (names + original ordinals)
  version_stubs.asm    MASM x64 jump stubs, one per non-forwarded export
  proxy_exports.inc    X-macro list consumed by proxy.cpp (index -> name)

Exports that the system DLL itself forwards (e.g. VerLanguageNameA ->
KERNEL32.VerLanguageNameA) are re-emitted as identical forwarders in the .def.
Every other export becomes a stub that jumps through sr2_proxy_table[i]; the
table slot is filled lazily (first call) by sr2_proxy_resolve(), which loads
the real DLL by full path from GetSystemDirectoryW().

Usage:  python proxy/gen_proxy.py [--source PATH]
"""
import argparse
import os
import sys

try:
    import pefile
except ImportError:
    sys.exit("pefile is required: python -m pip install pefile")

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SOURCE = os.path.join(os.environ.get("SystemRoot", r"C:\Windows"), "System32", "version.dll")
PREFIX = "sr2_proxy_"


def read_exports(path):
    pe = pefile.PE(path, fast_load=True)
    pe.parse_data_directories(directories=[pefile.DIRECTORY_ENTRY["IMAGE_DIRECTORY_ENTRY_EXPORT"]])
    if pe.FILE_HEADER.Machine != 0x8664:
        sys.exit(f"{path} is not x64 (machine=0x{pe.FILE_HEADER.Machine:x})")
    out = []
    for sym in pe.DIRECTORY_ENTRY_EXPORT.symbols:
        if not sym.name:
            sys.exit(f"ordinal-only export #{sym.ordinal} not supported by generator")
        out.append((sym.ordinal, sym.name.decode("ascii"),
                    sym.forwarder.decode("ascii") if sym.forwarder else None))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", default=DEFAULT_SOURCE)
    args = ap.parse_args()

    exports = read_exports(args.source)
    stubs = [(o, n) for (o, n, f) in exports if f is None]
    header = f"generated by proxy/gen_proxy.py from {args.source} - DO NOT EDIT"

    # ---- .def ------------------------------------------------------------
    lines = [f"; {header}", "LIBRARY version", "EXPORTS"]
    for ordinal, name, fwd in exports:
        target = fwd if fwd else PREFIX + name
        lines.append(f"    {name}={target} @{ordinal}")
    with open(os.path.join(HERE, "version.def"), "w", newline="\r\n") as f:
        f.write("\n".join(lines) + "\n")

    # ---- MASM stubs --------------------------------------------------------
    a = [f"; {header}",
         "OPTION CASEMAP:NONE",
         "",
         "EXTERN sr2_proxy_table:QWORD",
         "EXTERN sr2_proxy_resolve:PROC",
         "",
         ".code",
         "",
         "; Slow path: eax = export index. Preserves the 4 register args (rcx, rdx,",
         "; r8, r9); stack args are untouched because rsp is restored before the",
         "; tail jump. None of the proxied APIs take floating-point arguments.",
         "sr2_proxy_slow PROC FRAME",
         "    push rcx",
         "    .pushreg rcx",
         "    push rdx",
         "    .pushreg rdx",
         "    push r8",
         "    .pushreg r8",
         "    push r9",
         "    .pushreg r9",
         "    sub rsp, 28h",
         "    .allocstack 28h",
         "    .endprolog",
         "    mov ecx, eax",
         "    call sr2_proxy_resolve",
         "    add rsp, 28h",
         "    pop r9",
         "    pop r8",
         "    pop rdx",
         "    pop rcx",
         "    jmp rax",
         "sr2_proxy_slow ENDP",
         ""]
    for idx, (_, name) in enumerate(stubs):
        a += [f"{PREFIX}{name} PROC",
              f"    mov rax, QWORD PTR sr2_proxy_table[{idx * 8}]",
              "    test rax, rax",
              "    jz @F",
              "    jmp rax",
              "@@:",
              f"    mov eax, {idx}",
              "    jmp sr2_proxy_slow",
              f"{PREFIX}{name} ENDP",
              ""]
    a.append("END")
    with open(os.path.join(HERE, "version_stubs.asm"), "w", newline="\r\n") as f:
        f.write("\n".join(a) + "\n")

    # ---- X-macro list --------------------------------------------------------
    inc = [f"// {header}", "// SR2_PROXY_EXPORT(index, \"Name\")"]
    for idx, (_, name) in enumerate(stubs):
        inc.append(f"SR2_PROXY_EXPORT({idx}, \"{name}\")")
    with open(os.path.join(HERE, "proxy_exports.inc"), "w", newline="\r\n") as f:
        f.write("\n".join(inc) + "\n")

    fw = len(exports) - len(stubs)
    print(f"{len(exports)} exports ({len(stubs)} stubs, {fw} forwarders) from {args.source}")


if __name__ == "__main__":
    main()
