"""Embeds assets/icons/*.png into ui/mod_icons_data.inc (offline tool).

python gen_inc.py
The .inc defines one byte array per PNG and kEmbeddedIcons[] (name, data, size);
ui/mod_icons.cpp defines struct EmbeddedPng before including it.
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.normpath(os.path.join(HERE, "..", "..", "..", "ui", "mod_icons_data.inc"))


def main():
    names = sorted(f[:-4] for f in os.listdir(ICONS) if f.endswith(".png"))
    lines = ["// Generated by assets/icons/src/gen_inc.py from assets/icons/*.png - do not edit.", ""]
    for n in names:
        data = open(os.path.join(ICONS, n + ".png"), "rb").read()
        lines.append(f"static const unsigned char kPng_{n}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const EmbeddedPng kEmbeddedIcons[] = {")
    for n in names:
        lines.append(f'    {{"{n}", kPng_{n}, sizeof(kPng_{n})}},')
    lines.append("};")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(names), "icons")


if __name__ == "__main__":
    main()
