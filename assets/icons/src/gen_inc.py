"""Embeds the mod's icons into a C++ include (offline tool, stdlib only).

python gen_inc.py <out.inc>
Run by the CMake build (custom command, output build/generated/sr2mods_icons_data.inc); the
.inc is never committed. Embeds assets/icons/*.png plus assets/icons/local/*.png, the
gitignored local-only icons (the Hen / Elder Collector edits of game art), when that folder
exists, so a clean checkout builds without them.
The .inc defines one byte array per PNG and kEmbeddedIcons[] (name, data, size), ended by a
{nullptr, nullptr, 0} entry (so it is never empty); ui/mod_icons.cpp defines struct
EmbeddedPng before including it.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS = os.path.normpath(os.path.join(HERE, ".."))
LOCAL = os.path.join(ICONS, "local")


def pngs(folder):
    if not os.path.isdir(folder):
        return {}
    return {f[:-4]: os.path.join(folder, f) for f in os.listdir(folder) if f.lower().endswith(".png")}


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: gen_inc.py <out.inc>")
    out = os.path.abspath(sys.argv[1])
    icons = pngs(ICONS)
    local = pngs(LOCAL)
    clash = sorted(set(icons) & set(local))
    if clash:
        sys.exit("gen_inc.py: in both assets/icons and assets/icons/local: " + ", ".join(clash))
    icons.update(local)
    names = sorted(icons)
    lines = ["// Generated by assets/icons/src/gen_inc.py from assets/icons/*.png (+ local/) - do not edit.", ""]
    for n in names:
        data = open(icons[n], "rb").read()
        lines.append(f"static const unsigned char kPng_{n}[{len(data)}] = {{")
        for i in range(0, len(data), 24):
            lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
    lines.append("static const EmbeddedPng kEmbeddedIcons[] = {")
    for n in names:
        lines.append(f'    {{"{n}", kPng_{n}, sizeof(kPng_{n})}},')
    lines.append("    {nullptr, nullptr, 0},")
    lines.append("};")
    text = "\n".join(lines) + "\n"
    # Unchanged icons: leave the file alone, so nothing recompiles.
    if os.path.exists(out):
        with open(out, "r") as f:
            if f.read() == text:
                print("icons: up to date,", len(names), "embedded,", len(local), "local")
                return
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", newline="\n") as f:
        f.write(text)
    print("icons: wrote", out, "-", len(names), "embedded,", len(local), "local")


if __name__ == "__main__":
    main()
