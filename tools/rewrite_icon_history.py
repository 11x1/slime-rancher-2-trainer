"""Removes every AI- / script-drawn and game-derived icon from the whole git history.

Offline tool (Python 3 + git-filter-repo from PyPI: `python -m pip install --user git-filter-repo`).
It never touches the source repository: it makes a fresh `git clone --mirror --no-local` of it in
a scratch folder, rewrites that clone, and verifies it. Pushing the result is a separate, manual
step (.claude/notes/history-rewrite.md).

    python -P tools/rewrite_icon_history.py --work <scratch dir> [--source <repo>]
           [--simulate-merge <branch>] [--build]

  --source          repository to clone (default: the main checkout this script lives in)
  --work            scratch folder, must not exist yet; the rewritten bare repo is <work>/mirror.git
  --simulate-merge  dry run only: first merge <branch> into develop inside the clone (as the
                    orchestrator will), so check (b) compares against the merged tree
  --build           check (c): check develop out of the rewritten clone and run build.ps1 there

What goes (see .claude/notes/history-rewrite.md for the evidence per file):
  * REMOVE_PATHS: every version of these paths, in every commit of every ref;
  * STRIP_BLOBS: the script-drawn first versions of four paths whose later versions are the
    user's drawings (ash_boost, growth_1, mods_tab, plort_door): only those blobs go.
Checks after the rewrite:
  (a) no removed path and no removed blob is left (`git rev-list --objects --all`, plus every
      object in the pack), and every image blob left is one of the user's drawings;
  (b) develop's tree is the same tree as before the rewrite (after the simulated merge), and so
      is every branch / tag tip whose tree held nothing removed (refs/remotes/* of the source,
      i.e. its stale origin/* copies, are dropped by filter-repo and not pushed anyway);
  (c) with --build, develop builds from a clean checkout (no generated .inc, no local icons).
"""

import argparse
import os
import subprocess
import sys
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))

# Every version of these is removed.
REMOVE_PATHS = [
    # generated byte arrays of all embedded icons (including the removed ones); now built at build time
    "ui/mod_icons_data.inc",
    # the script that drew the AI / script-drawn icons and its drawing helpers
    "assets/icons/src/make_icons.py",
    "assets/icons/src/iconkit.py",
    # script-drawn icons (make_icons.py), commit 5683616 "Add custom mod icons and their generator scripts"
    "assets/icons/collector_2.png",
    "assets/icons/collector_3.png",
    "assets/icons/coop_air_net.png",
    "assets/icons/feeder_2.png",
    "assets/icons/growth_2.png",
    "assets/icons/hen_collector.png",
    "assets/icons/hens_1.png",
    "assets/icons/hens_2.png",
    "assets/icons/music_2.png",
    "assets/icons/sell_all.png",
    "assets/icons/sell_all_now.png",
    # script-drawn tracker icons (c321aa0, 6c8422c) and their later *_placeholder copies (9d5f497)
    "assets/icons/gordo.png",
    "assets/icons/shadow_door.png",
    "assets/icons/ghost_drone.png",
    "assets/icons/map_node.png",
    "assets/icons/research_drone.png",
    "assets/icons/ghost_drone_placeholder.png",
    "assets/icons/map_node_placeholder.png",
    "assets/icons/research_drone_placeholder.png",
    # the user's edits of the game's collector body (game art): local-only from now on
    "assets/icons/hen_collector_source.png",
    "assets/icons/elder_collector_source.png",
    "assets/icons/source/hencollector_custom.png",
    "assets/icons/source/roostercollector_custom.png",
    "assets/icons/source/eldercollector_custom.png",
]

# Script-drawn first versions of paths the user's drawing later replaced (5683616, c321aa0).
STRIP_BLOBS = {
    "28f6149edcfd5b843959e6302976c02758c84f96": "assets/icons/ash_boost.png (script-drawn, 5683616)",
    "457b1f1dcf4fc191e9def0056046d454a699a19a": "assets/icons/growth_1.png (script-drawn, 5683616)",
    "cef6a7c215caeb06db1955d05cf72d9f855d477f": "assets/icons/mods_tab.png (script-drawn, 5683616)",
    "a95781f6ffbb1fcc606fceafd8a6738dfc9d7d9a": "assets/icons/plort_door.png (script-drawn, c321aa0)",
}

IMAGE_EXT = (".png", ".jpg", ".jpeg", ".gif", ".bmp", ".tga", ".psd", ".webp", ".ico", ".pdf")


def run(args, cwd=None, check=True, text=True):
    r = subprocess.run(args, cwd=cwd, capture_output=True, text=text, encoding="utf-8" if text else None)
    if check and r.returncode != 0:
        sys.exit(f"failed ({r.returncode}): {' '.join(args)}\n{r.stdout}\n{r.stderr}")
    return r


def git(repo, *args, check=True):
    return run(["git", "-C", repo, *args], check=check).stdout


def path_blobs(repo):
    """Every (path, blob) pair that ever existed in any ref."""
    out = git(repo, "log", "--all", "--no-renames", "--raw", "--no-abbrev", "--format=")
    pairs = defaultdict(set)
    for line in out.splitlines():
        if not line.startswith(":"):
            continue
        meta, path = line.split("\t", 1)
        f = meta.split()
        for blob in (f[2], f[3]):
            if set(blob) != {"0"}:
                pairs[path].add(blob)
    return pairs


def all_objects(repo):
    out = git(repo, "cat-file", "--batch-all-objects", "--batch-check=%(objectname) %(objecttype)")
    return {l.split()[0]: l.split()[1] for l in out.splitlines() if l}


def tree_has_removed(repo, ref, rm_paths, rm_blobs):
    out = git(repo, "ls-tree", "-r", ref)
    for line in out.splitlines():
        meta, path = line.split("\t", 1)
        if path in rm_paths or meta.split()[2] in rm_blobs:
            return True
    return False


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--source", default=None)
    ap.add_argument("--work", required=True)
    ap.add_argument("--simulate-merge", default=None)
    ap.add_argument("--build", action="store_true")
    a = ap.parse_args()
    sys.stdout.reconfigure(line_buffering=True)

    if run([sys.executable, "-m", "git_filter_repo", "--version"], check=False).returncode != 0:
        sys.exit("git-filter-repo missing: python -m pip install --user git-filter-repo")
    source = a.source or git(HERE, "rev-parse", "--path-format=absolute", "--git-common-dir").strip()
    source = os.path.abspath(source)
    work = os.path.abspath(a.work)
    if os.path.exists(work):
        sys.exit(f"{work} exists: give a new, empty scratch folder")
    if os.path.commonpath([work, source]) == source:
        sys.exit("the scratch folder must be outside the source repository")
    os.makedirs(work)
    mirror = os.path.join(work, "mirror.git")

    print(f"[1] clone --mirror --no-local {source}")
    run(["git", "clone", "--mirror", "--no-local", "--quiet", source, mirror])
    refs_before = git(mirror, "for-each-ref", "--format=%(refname) %(objectname) %(objecttype)").splitlines()
    commits_before = int(git(mirror, "rev-list", "--all", "--count"))
    print(f"    {len(refs_before)} refs, {commits_before} commits")

    if a.simulate_merge:
        print(f"[2] simulate: merge {a.simulate_merge} into develop (inside the clone only)")
        tree = git(mirror, "merge-tree", "--write-tree", "develop", a.simulate_merge).split()[0]
        commit = run(["git", "-C", mirror, "commit-tree", tree, "-p", "develop", "-p", a.simulate_merge,
                      "-m", f"Merge {a.simulate_merge} into develop (simulated)"]).stdout.strip()
        git(mirror, "update-ref", "refs/heads/develop", commit)
        print(f"    develop -> {commit[:10]}, tree {tree[:10]}")

    # what goes
    pairs = path_blobs(mirror)
    rm_paths = set(REMOVE_PATHS)
    rm_blobs = set(STRIP_BLOBS)
    for p in rm_paths:
        rm_blobs |= pairs.get(p, set())
    unknown = sorted(p for p in rm_paths if p not in pairs)
    image_paths = sorted(p for p in pairs if p.lower().endswith(IMAGE_EXT))
    keep_blobs = set()
    for p in image_paths:
        if p not in rm_paths:
            keep_blobs |= pairs[p] - set(STRIP_BLOBS)
    clash = keep_blobs & rm_blobs
    if clash:
        sys.exit(f"a blob to remove is also a kept file's content: {sorted(clash)}")
    print(f"[3] remove {len(rm_paths)} paths ({len(unknown)} never existed), {len(rm_blobs)} blobs "
          f"({len(STRIP_BLOBS)} by id); keep {len(keep_blobs)} image blobs")
    for p in unknown:
        print("    (not in history:", p + ")")

    # expected trees: develop (merged) and every tip that holds nothing removed stays the same tree
    expect, dirty = {}, []
    for line in git(mirror, "for-each-ref", "--format=%(refname) %(objecttype)").splitlines():
        ref, typ = line.split()
        if typ != "commit" or ref.startswith("refs/remotes/"):
            continue  # filter-repo drops the clone's copies of the source's remote-tracking refs
        if ref == "refs/heads/develop" or not tree_has_removed(mirror, ref, rm_paths, rm_blobs):
            expect[ref] = git(mirror, "rev-parse", ref + "^{tree}").strip()
        else:
            dirty.append(ref)
    with open(os.path.join(work, "tips-with-removed-files.txt"), "w", newline="\n") as f:
        f.write("".join(r + "\n" for r in dirty))
    print(f"    {len(dirty)} branch tips still hold removed files (their tip trees will change: merge or "
          f"drop those branches before the real run; list in tips-with-removed-files.txt)")
    if tree_has_removed(mirror, "refs/heads/develop", rm_paths, rm_blobs):
        print("    WARNING: develop still holds removed files (merge chore/icons-custom-only first)")

    print("[4] git filter-repo")
    pf = os.path.join(work, "remove-paths.txt")
    bf = os.path.join(work, "strip-blobs.txt")
    with open(pf, "w", newline="\n") as f:
        f.write("".join(f"literal:{p}\n" for p in REMOVE_PATHS))
    with open(bf, "w", newline="\n") as f:
        f.write("".join(f"{b}\n" for b in sorted(STRIP_BLOBS)))
    r = run([sys.executable, "-m", "git_filter_repo", "--force", "--sensitive-data-removal", "--no-fetch",
             "--replace-refs", "delete-no-add",
             "--invert-paths", "--paths-from-file", pf, "--strip-blobs-with-ids", bf], cwd=mirror, check=False)
    with open(os.path.join(work, "filter-repo.log"), "w", encoding="utf-8") as f:
        f.write(r.stdout + "\n" + r.stderr)
    if r.returncode != 0:
        sys.exit(f"filter-repo failed, see {work}/filter-repo.log")
    # drop everything unreachable, so the object check below sees only what a push could send
    git(mirror, "reflog", "expire", "--expire=now", "--all")
    git(mirror, "gc", "--prune=now", "--quiet")
    commits_after = int(git(mirror, "rev-list", "--all", "--count"))
    refs_after = git(mirror, "for-each-ref", "--format=%(refname)").splitlines()
    print(f"    {len(refs_after)} refs, {commits_after} commits ({commits_before - commits_after} empty ones dropped)")

    ok = True
    print("[5] check (a): nothing removed is left")
    listed = git(mirror, "rev-list", "--objects", "--all").splitlines()
    left_paths = sorted({l.split(" ", 1)[1] for l in listed if " " in l and l.split(" ", 1)[1] in rm_paths})
    left_blobs = sorted({l.split(" ", 1)[0] for l in listed} & rm_blobs)
    objs = all_objects(mirror)
    left_any = sorted(set(objs) & rm_blobs)
    pairs_after = path_blobs(mirror)
    img_after = set()
    for p, bs in pairs_after.items():
        if p.lower().endswith(IMAGE_EXT):
            img_after |= bs
    stray = sorted(img_after - keep_blobs)
    print(f"    paths left: {len(left_paths)}, removed blobs reachable: {len(left_blobs)}, "
          f"in the object store at all: {len(left_any)}, image blobs left: {len(img_after)} "
          f"(not in the keep list: {len(stray)}), objects: {len(objs)}")
    for x in left_paths + left_blobs + left_any + stray:
        print("    LEFT:", x)
    ok &= not (left_paths or left_blobs or left_any or stray)

    print("[6] check (b): trees unchanged")
    bad = 0
    for ref, tree in sorted(expect.items()):
        now = git(mirror, "rev-parse", "--verify", "--quiet", ref + "^{tree}", check=False).strip()
        if now != tree:
            bad += 1
            print(f"    CHANGED: {ref} {tree[:10]} -> {now[:10] or '(gone)'}")
    dev = git(mirror, "rev-parse", "refs/heads/develop^{tree}").strip()
    print(f"    {len(expect) - bad}/{len(expect)} refs keep their tree; develop tree {dev[:10]} "
          f"{'== before' if expect.get('refs/heads/develop') == dev else '!= before'}")
    ok &= bad == 0

    if a.build:
        print("[7] check (c): clean build of develop")
        wt = os.path.join(work, "check")
        git(mirror, "worktree", "add", "--quiet", "--detach", wt, "develop")
        # build.ps1 skips the agent build lock when the source repo allows parallel builds
        if git(source, "config", "--get", "sr2mods.parallelbuilds", check=False).strip() == "true":
            git(mirror, "config", "sr2mods.parallelbuilds", "true")
        b = run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File", os.path.join(wt, "build.ps1")],
                cwd=wt, check=False)
        with open(os.path.join(work, "build.log"), "w", encoding="utf-8") as f:
            f.write(b.stdout + "\n" + b.stderr)
        icons = [l for l in b.stdout.splitlines() if "icons:" in l]
        print(f"    build.ps1 exit {b.returncode}; {icons[-1].strip() if icons else 'no icons line'}; log {work}\\build.log")
        ok &= b.returncode == 0

    print("[done]", "ALL CHECKS PASSED" if ok else "CHECKS FAILED", "-", mirror)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
